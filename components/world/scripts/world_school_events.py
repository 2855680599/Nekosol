#!/usr/bin/env python3
"""Bounded, deterministic school events for the Shiomi World.

This module is a small World-fact layer.  Events are derived from a bounded
date rule and a durable feature epoch; they are not generated by an LLM and
do not create actions, Timeline processes, Experience, Memory, or messages.
The only durable event-layer state is the epoch that prevents activation from
backfilling earlier school days.
"""

